export const DIRECTIONS = Object.keys(DIRECTION_PROMPTS);

export const BRAND_LIMITS = {
  name: 100, product: 500, audience: 500, usp: 300, competitors: 300, tone: 200, geo: 100, budget: 100,
};
const BRAND_LABELS = {
  name: 'Бренд', product: 'Продукт', audience: 'Целевая аудитория', usp: 'УТП',
  competitors: 'Конкуренты', tone: 'Tone of voice', geo: 'География', budget: 'Бюджет',
};

export function cleanBrand(raw) {
  const brand = {};
  if (!raw || typeof raw !== 'object') return brand;
  for (const [key, max] of Object.entries(BRAND_LIMITS)) {
    const value = typeof raw[key] === 'string' ? raw[key].trim().slice(0, max) : '';
    if (value) brand[key] = value;
  }
  return brand;
}

export function buildSystemPrompt(direction, brand) {
  const blocks = [{ type: 'text', text: BASE_PROMPT }, { type: 'text', text: DIRECTION_PROMPTS[direction] }];
  const lines = Object.entries(brand).map(([k, v]) => `${BRAND_LABELS[k]}: ${v}`);
  blocks.push({
    type: 'text',
    text: lines.length
      ? `Профиль бренда пользователя (учитывай его в ответах):\n<brand>\n${lines.join('\n')}\n</brand>`
      : 'Профиль бренда не заполнен. Если для ответа нужен контекст бизнеса, спроси или сделай допущения.',
  });
  return blocks;
}
